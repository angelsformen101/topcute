<script>
  'use strict';

  function initTheme() {
    const saved = localStorage.getItem('tcg_admin_theme') || 'dark';
    applyTheme(saved);
  }

  function applyTheme(theme) {
    const isDark = theme === 'dark';
    if (isDark) {
      document.documentElement.classList.add('dark');
    } else {
      document.documentElement.classList.remove('dark');
    }
    localStorage.setItem('tcg_admin_theme', theme);

    document.querySelectorAll('.theme-toggle-btn').forEach(btn => {
      const icon = btn.querySelector('[data-theme-icon]');
      const label = btn.querySelector('[data-theme-label]');
      if (isDark) {
        if (icon) {
          icon.setAttribute('data-lucide', 'sun');
          icon.className = 'w-4 h-4 text-amber-500';
        }
        if (label) label.textContent = 'Light';
        btn.setAttribute('title', 'Switch to Light Theme');
      } else {
        if (icon) {
          icon.setAttribute('data-lucide', 'moon');
          icon.className = 'w-4 h-4 text-zinc-600 dark:text-zinc-300';
        }
        if (label) label.textContent = 'Dark';
        btn.setAttribute('title', 'Switch to Dark Theme');
      }
    });

    if (window.lucide) lucide.createIcons();
  }

  function toggleTheme() {
    const isDark = document.documentElement.classList.contains('dark');
    applyTheme(isDark ? 'light' : 'dark');
  }

  document.addEventListener('DOMContentLoaded', () => {
    initTheme();
    if (window.lucide) lucide.createIcons();
  });

  function togglePass(id) {
    const input = document.getElementById(id);
    input.type = input.type === 'password' ? 'text' : 'password';
  }

  function setViewMode(mode) {
    const cardsBtn = document.getElementById('php-view-cards-btn');
    const tableBtn = document.getElementById('php-view-table-btn');
    const cardsCont = document.getElementById('php-cards-container');
    const tableCont = document.getElementById('php-table-container');

    if (mode === 'cards') {
      cardsBtn.className = 'p-1.5 rounded-md text-zinc-900 dark:text-white bg-white dark:bg-zinc-800 shadow-xs cursor-pointer transition-colors';
      tableBtn.className = 'p-1.5 rounded-md text-zinc-500 hover:text-zinc-900 dark:text-zinc-400 dark:hover:text-white cursor-pointer transition-colors';
      cardsCont.classList.remove('hidden');
      tableCont.classList.add('hidden');
    } else {
      tableBtn.className = 'p-1.5 rounded-md text-zinc-900 dark:text-white bg-white dark:bg-zinc-800 shadow-xs cursor-pointer transition-colors';
      cardsBtn.className = 'p-1.5 rounded-md text-zinc-500 hover:text-zinc-900 dark:text-zinc-400 dark:hover:text-white cursor-pointer transition-colors';
      tableCont.classList.remove('hidden');
      cardsCont.classList.add('hidden');
    }
  }

  let activeRegion = 'ALL';
  function setRegionFilter(region, btn) {
    activeRegion = region;
    document.querySelectorAll('.php-region-pill').forEach(b => {
      if (b === btn) {
        b.className = 'php-region-pill px-3 py-1 rounded-md font-medium transition-colors cursor-pointer bg-blue-600 text-white';
      } else {
        b.className = 'php-region-pill px-3 py-1 rounded-md font-medium transition-colors cursor-pointer bg-zinc-100 dark:bg-zinc-800 text-zinc-600 dark:text-zinc-300 hover:bg-zinc-200 dark:hover:bg-zinc-700';
      }
    });
    filterPages();
  }

  function filterPages() {
    const query = (document.getElementById('php-search-input').value || '').toLowerCase().trim();
    const cards = document.querySelectorAll('.page-card');
    const rows = document.querySelectorAll('.page-row');
    let visibleCount = 0;

    cards.forEach(card => {
      const name = card.getAttribute('data-name') || '';
      const filename = card.getAttribute('data-filename') || '';
      const city = card.getAttribute('data-city') || '';
      const phone = card.getAttribute('data-phone') || '';
      const region = card.getAttribute('data-region') || '';

      const matchReg = (activeRegion === 'ALL' || region === activeRegion);
      const matchSearch = !query || name.includes(query) || filename.includes(query) || city.includes(query) || phone.includes(query);

      if (matchReg && matchSearch) {
        card.classList.remove('hidden');
        visibleCount++;
      } else {
        card.classList.add('hidden');
      }
    });

    rows.forEach(row => {
      const name = row.getAttribute('data-name') || '';
      const filename = row.getAttribute('data-filename') || '';
      const city = row.getAttribute('data-city') || '';
      const phone = row.getAttribute('data-phone') || '';
      const region = row.getAttribute('data-region') || '';

      const matchReg = (activeRegion === 'ALL' || region === activeRegion);
      const matchSearch = !query || name.includes(query) || filename.includes(query) || city.includes(query) || phone.includes(query);

      if (matchReg && matchSearch) row.classList.remove('hidden');
      else row.classList.add('hidden');
    });

    const badge = document.getElementById('filtered-count-badge');
    if (badge) badge.textContent = 'Showing ' + visibleCount + ' pages';
  }

  function openEditModal(pageData) {
    document.getElementById('modal-page-id').value = pageData.id;
    document.getElementById('modal-page-title').innerText = pageData.name;
