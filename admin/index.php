    const sameToggle = document.getElementById('modal-same-wa-toggle');

    phoneInput.value = pageData.phone || '000000000';
    waInput.value = pageData.whatsapp || ('91' + (pageData.phone || '000000000'));

    const cleanPhone = (pageData.phone || '').replace(/[^0-9]/g, '');
    const cleanWa = (pageData.whatsapp || '').replace(/[^0-9]/g, '');
    const isSame = (cleanWa === '91' + cleanPhone || cleanWa === cleanPhone || !cleanWa);

    sameToggle.checked = isSame;
    toggleSameWhatsApp();
    updatePreviewBox();

    phoneInput.oninput = () => {
      if (sameToggle.checked) syncWhatsAppAuto();
      updatePreviewBox();
    };

    document.getElementById('edit-modal').classList.remove('hidden');
    if (window.lucide) lucide.createIcons();
  }

