        if ($action === 'logout') {
            unset($_SESSION['admin_auth_user']);
            session_destroy();
            header("Location: index.php");
            exit;
        }

        // Action: Update Single Page
        if ($action === 'update_single_page') {
            $page_id = trim($_POST['page_id'] ?? '');
            $new_phone = trim($_POST['phone'] ?? '');
            $new_wa = trim($_POST['whatsapp'] ?? '');

