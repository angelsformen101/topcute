                $contacts[$page_id]['last_updated'] = date('Y-m-d H:i:s');

                save_contacts_data($contacts);
                sync_master_variables($contacts);

                if (!empty($_POST['is_ajax'])) {
                    header('Content-Type: application/json');
                    echo json_encode([
                        'status' => 'success',
                        'message' => "Contact details for {$contacts[$page_id]['name']} updated successfully!",
                        'data' => $contacts[$page_id]
                    ]);
                    exit;
                }

                $message = "Contact number updated successfully for {$contacts[$page_id]['name']}!";
                $message_type = "success";
            } else {
                $message = "Page '{$page_id}' not found in registry.";
                $message_type = "error";
            }
        }

        // Action: Bulk Update All Pages
        if ($action === 'update_bulk_pages') {
            $bulk_phone = trim($_POST['bulk_phone'] ?? '');
            $bulk_wa = trim($_POST['bulk_whatsapp'] ?? '');
            $scope = $_POST['scope'] ?? 'all'; // 'all' or 'placeholders_only'

            if (!empty($bulk_phone)) {
                $clean_phone = clean_phone_number($bulk_phone);
                $clean_wa = !empty($bulk_wa) ? clean_phone_number($bulk_wa) : format_whatsapp_number($clean_phone);
                if (strlen($clean_wa) === 10) {
                    $clean_wa = '91' . $clean_wa;
                }

                $contacts = get_contacts_data();
                $updated_count = 0;

                foreach ($contacts as $id => &$p) {
                    if ($scope === 'placeholders_only' && $p['is_custom']) {
                        continue; // Skip pages that already have custom numbers
                    }

                    $p['phone'] = $clean_phone;
                    $p['whatsapp'] = $clean_wa;
                    $p['display_format'] = format_display_phone($clean_phone);
                    $p['is_custom'] = ($clean_phone !== '000000000');
                    $p['last_updated'] = date('Y-m-d H:i:s');
                    $updated_count++;
                }

