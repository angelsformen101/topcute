// Scanner: Scans all HTML files in website root
// -------------------------------------------------------------------------
function scan_website_html_files() {
    $pages = [];
    $html_files = glob(ROOT_DIR . DIRECTORY_SEPARATOR . '*.html');

    if (!$html_files) {
        return $pages;
    }

    foreach ($html_files as $file_path) {
        $filename = basename($file_path);
        // Exclude redirect/error page
        if ($filename === '404.html') {
            continue;
        }

        $content = @file_get_contents($file_path);
        if ($content === false) {
            continue;
        }

        // Title
        $title = '';
        if (preg_match('/<title>(.*?)<\/title>/is', $content, $m)) {
            $title = trim($m[1]);
        }

        // Tel matches
        preg_match_all('/href="tel:([^"]+)"/i', $content, $tel_matches);
        $tels = !empty($tel_matches[1]) ? array_values(array_unique(array_map('trim', $tel_matches[1]))) : [];

        // WhatsApp matches
        preg_match_all('/wa\.me\/([0-9]+)/i', $content, $wa_matches);
        $was = !empty($wa_matches[1]) ? array_values(array_unique(array_map('trim', $wa_matches[1]))) : [];

        // Schema telephone
        preg_match('/"telephone":\s*"([^"]+)"/i', $content, $schema_match);
        $schema_phone = !empty($schema_match[1]) ? trim($schema_match[1]) : '';

        // Determine primary numbers
        $primary_phone = '000000000';
        if (!empty($tels)) {
            // Find non-placeholder if exists
            foreach ($tels as $t) {
                $clean_t = preg_replace('/[^0-9]/', '', $t);
                if (!empty($clean_t) && $clean_t !== '000000000' && $clean_t !== '91000000000') {
                    $primary_phone = $clean_t;
                    break;
                }
            }
            if ($primary_phone === '000000000' && !empty($tels[0])) {
                $primary_phone = preg_replace('/[^0-9]/', '', $tels[0]);
            }
        }

        $primary_whatsapp = '91000000000';
        if (!empty($was)) {
            foreach ($was as $w) {
                if ($w !== '91000000000') {
                    $primary_whatsapp = $w;
                    break;
                }
            }
            if ($primary_whatsapp === '91000000000' && !empty($was[0])) {
                $primary_whatsapp = $was[0];
            }
        }

        // Normalization
        $is_custom = ($primary_phone !== '000000000' && !empty($primary_phone));
        $clean_phone = preg_replace('/[^0-9]/', '', $primary_phone);
        if (strlen($clean_phone) === 12 && substr($clean_phone, 0, 2) === '91') {
            $ten_digit = substr($clean_phone, 2);
        } else {
            $ten_digit = $clean_phone;
        }

        $meta = get_page_metadata($filename);
        $id = pathinfo($filename, PATHINFO_FILENAME);

        $display_format = '+91-' . (strlen($ten_digit) === 10 ? $ten_digit : $clean_phone);

        $pages[$id] = [
            'id' => $id,
            'filename' => $filename,
            'name' => $meta['name'],
            'city' => $meta['city'],
            'region' => $meta['region'],
            'title' => $title,
            'phone' => $ten_digit,
            'whatsapp' => $primary_whatsapp,
            'display_format' => $display_format,
            'is_custom' => $is_custom,
            'tel_links_count' => count($tel_matches[1] ?? []),
            'wa_links_count' => count($wa_matches[1] ?? []),
            'schema_phone' => $schema_phone,
            'last_updated' => date('Y-m-d H:i:s')
        ];
    }

    // Sort by Region, then Name
    uasort($pages, function($a, $b) {
        if ($a['region'] === $b['region']) {
            return strcmp($a['name'], $b['name']);
        }
        return strcmp($a['region'], $b['region']);
    });

    return $pages;
}

