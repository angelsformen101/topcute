function get_contacts_data() {
    if (!file_exists(CONTACTS_FILE)) {
        $initial_pages = scan_website_html_files();
        save_contacts_data($initial_pages);
        return $initial_pages;
    }

    $raw = @file_get_contents(CONTACTS_FILE);
    $data = json_decode($raw, true);

    if (!is_array($data) || empty($data)) {
        $initial_pages = scan_website_html_files();
        save_contacts_data($initial_pages);
        return $initial_pages;
    }

    return $data;
}

function save_contacts_data($data) {
    return @file_put_contents(
        CONTACTS_FILE,
        json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
        LOCK_EX
    ) !== false;
}

// Format phone helper
function clean_phone_number($number) {
    return preg_replace('/[^0-9]/', '', $number);
}

function format_whatsapp_number($number) {
    $clean = clean_phone_number($number);
    if (strlen($clean) === 10) {
        return '91' . $clean;
    }
    return $clean;
}

function format_display_phone($number) {
    $clean = clean_phone_number($number);
    if (strlen($clean) === 12 && substr($clean, 0, 2) === '91') {
        return '+91-' . substr($clean, 2);
    }
    if (strlen($clean) === 10) {
        return '+91-' . $clean;
    }
    return '+91-' . $clean;
}

